#!/usr/bin/env node
// Extract advance widths from the bundled Excalifont TrueType file and write
// them to `src/layout/font_metrics.mjs`. The output is committed so text
// measurement works without reading binary assets at runtime (and in browsers).
//
// Usage: node scripts/gen-font-metrics.mjs [--check]

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const buf = readFileSync(path.join(root, "assets/fonts/Excalifont-Regular.ttf"));

const u16 = (o) => buf.readUInt16BE(o);
const i16 = (o) => buf.readInt16BE(o);
const u32 = (o) => buf.readUInt32BE(o);

/** @type {Record<string, number>} */
const tables = {};
const numTables = u16(4);
for (let i = 0; i < numTables; i++) {
  const rec = 12 + i * 16;
  tables[buf.toString("ascii", rec, rec + 4)] = u32(rec + 8);
}

const unitsPerEm = u16(tables.head + 18);
const ascender = i16(tables.hhea + 4);
const descender = i16(tables.hhea + 6);
const numHMetrics = u16(tables.hhea + 34);

/** @param {number} glyph */
function advance(glyph) {
  const idx = Math.min(glyph, numHMetrics - 1);
  return u16(tables.hmtx + idx * 4);
}

// cmap: pick the Windows Unicode BMP (format 4) subtable.
const cmap = tables.cmap;
let sub = 0;
for (let i = 0; i < u16(cmap + 2); i++) {
  const rec = cmap + 4 + i * 8;
  const platform = u16(rec);
  const encoding = u16(rec + 2);
  const offset = cmap + u32(rec + 4);
  if (
    u16(offset) === 4 &&
    (platform === 3 || platform === 0) &&
    (encoding === 1 || platform === 0)
  ) {
    sub = offset;
    break;
  }
}
if (!sub) throw new Error("No format-4 cmap subtable found");

const segX2 = u16(sub + 6);
const endCodes = sub + 14;
const startCodes = endCodes + segX2 + 2;
const idDeltas = startCodes + segX2;
const idRangeOffsets = idDeltas + segX2;

/** @type {Map<number, number>} */
const widths = new Map();
for (let s = 0; s < segX2 / 2; s++) {
  const end = u16(endCodes + s * 2);
  const start = u16(startCodes + s * 2);
  const delta = i16(idDeltas + s * 2);
  const rangeOffsetPos = idRangeOffsets + s * 2;
  const rangeOffset = u16(rangeOffsetPos);
  for (let c = start; c <= end && c !== 0xffff; c++) {
    let glyph;
    if (rangeOffset === 0) glyph = (c + delta) & 0xffff;
    else {
      const g = u16(rangeOffsetPos + rangeOffset + (c - start) * 2);
      glyph = g === 0 ? 0 : (g + delta) & 0xffff;
    }
    if (glyph !== 0) widths.set(c, advance(glyph));
  }
}

const entries = [...widths.entries()].sort((a, b) => a[0] - b[0]);
const fallback = Math.round(
  entries.filter(([c]) => c >= 0x61 && c <= 0x7a).reduce((sum, [, w]) => sum + w, 0) / 26,
);

const lines = [
  "// Generated by scripts/gen-font-metrics.mjs from assets/fonts/Excalifont-Regular.ttf.",
  "// Do not edit by hand.",
  "",
  `export const UNITS_PER_EM = ${unitsPerEm};`,
  `export const ASCENDER = ${ascender};`,
  `export const DESCENDER = ${descender};`,
  `export const FALLBACK_ADVANCE = ${fallback};`,
  "",
  "/** Code point → advance width in font units, as flat [codePoint, width] pairs. */",
  `export const ADVANCES = [${entries.map(([c, w]) => `${c},${w}`).join(",")}];`,
  "",
];
const target = path.join(root, "src/layout/font_metrics.mjs");
const generated = lines.join("\n");
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") === generated) {
    console.log("Font metrics are up to date.");
  } else {
    console.error("Font metrics are stale. Run node scripts/gen-font-metrics.mjs.");
    process.exitCode = 1;
  }
} else {
  writeFileSync(target, generated);
  console.log(`Wrote ${entries.length} glyph widths (unitsPerEm=${unitsPerEm}).`);
}
