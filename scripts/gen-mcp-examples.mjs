#!/usr/bin/env node
// Embed the bundled examples (examples/<kind>/*.puml) into
// `src/mcp/examples.generated.mjs`. The npm package does not ship `examples/`,
// so the MCP `get_example` tool reads its inventory from this generated module.
// The output is committed and formatted with the repository's Prettier config.
//
// Usage:
//   node scripts/gen-mcp-examples.mjs           write the module
//   node scripts/gen-mcp-examples.mjs --check   fail when the module is stale

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";
import * as prettier from "prettier";
import { detectKind } from "../src/index.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const examplesDir = path.join(root, "examples");
const target = path.join(root, "src", "mcp", "examples.generated.mjs");

/** Plain code-point order keeps the output independent of the locale. */
const byCodePoint = (/** @type {string} */ a, /** @type {string} */ b) =>
  a < b ? -1 : a > b ? 1 : 0;

/**
 * @returns {{ kind: string, name: string, diagram: string, source: string }[]}
 */
function collect() {
  const out = [];
  const kinds = readdirSync(examplesDir, { withFileTypes: true })
    .filter((e) => e.isDirectory())
    .map((e) => e.name)
    .sort(byCodePoint);
  for (const kind of kinds) {
    const files = readdirSync(path.join(examplesDir, kind))
      .filter((f) => f.endsWith(".puml"))
      .sort(byCodePoint);
    for (const file of files) {
      const source = readFileSync(path.join(examplesDir, kind, file), "utf8").replace(
        /\r\n/g,
        "\n",
      );
      out.push({ kind, name: file.slice(0, -".puml".length), diagram: detectKind(source), source });
    }
  }
  return out;
}

async function generate() {
  const body = `// Generated by scripts/gen-mcp-examples.mjs from examples/. Do not edit.
/**
 * @typedef {object} BundledExample
 * @property {string} kind Example folder, e.g. \`sequence\`.
 * @property {string} name File name without the \`.puml\` extension.
 * @property {string} diagram Diagram kind detected by excaliplant.
 * @property {string} source PlantUML source.
 */

/** @type {readonly BundledExample[]} */
export const EXAMPLES = Object.freeze(${JSON.stringify(collect())});
`;
  const config = (await prettier.resolveConfig(target)) ?? {};
  return prettier.format(body, { ...config, filepath: target });
}

const next = await generate();
if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(target, "utf8");
  } catch {
    // Missing file counts as stale.
  }
  if (current !== next) {
    process.stderr.write(
      "src/mcp/examples.generated.mjs is stale. Run `node scripts/gen-mcp-examples.mjs`.\n",
    );
    process.exit(1);
  }
  process.stdout.write("src/mcp/examples.generated.mjs is up to date.\n");
} else {
  writeFileSync(target, next);
  process.stdout.write(`Wrote ${path.relative(root, target)}\n`);
}
