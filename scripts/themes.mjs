import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { createThemeRegistry } from "../src/draw/theme_registry.mjs";

import { assertThemeContrast } from "./theme_contrast.mjs";
import { checkThemeInventory, parseThemeDefinition } from "./theme_inventory.mjs";

const folder = new URL("../src/draw/themes/", import.meta.url);
const historicalOrder = ["base", "sketch", "plain", "hachure", "mono", "dark", "blueprint"];
const filenames = readdirSync(folder)
  .filter((file) => file.endsWith(".json"))
  .sort();
const ordered = filenames.sort((a, b) => {
  const rank = (file) => {
    const position = historicalOrder.indexOf(file.slice(0, -5));
    return position === -1 ? historicalOrder.length : position;
  };
  return rank(a) - rank(b);
});
const definitions = ordered.map((file) => {
  const value = parseThemeDefinition(readFileSync(new URL(file, folder), "utf8"), file);
  if (value.id + ".json" !== file) throw new Error(`Theme ID must match filename: ${file}`);
  return value;
});
for (const definition of createThemeRegistry(definitions).values()) assertThemeContrast(definition);
checkThemeInventory(new URL("../src/", import.meta.url), definitions[0]);
const output = new URL("definitions.generated.mjs", folder);
const source = [
  "// Generated by scripts/themes.mjs.",
  '/** @type {import("../theme_registry.mjs").ThemeDefinition[]} */',
  `export const definitions = ${JSON.stringify(definitions, null, 2)};`,
  "",
].join("\n");
const { format, resolveConfig } = await import("prettier");
const formatted = await format(source, {
  ...(await resolveConfig(output.pathname)),
  parser: "babel",
});
const manifest = new URL("../integrations/vscode/package.json", import.meta.url);
const manifestText = readFileSync(manifest, "utf8");
const pkg = JSON.parse(manifestText);
const setting = pkg.contributes.configuration.properties["excaliplant.theme"];
const descriptions = new Map(
  setting.enum.map((id, index) => [id, setting.enumDescriptions[index]]),
);
setting.enum = ["auto", ...definitions.slice(1).map(({ id }) => id)];
setting.enumDescriptions = setting.enum.map((id) => descriptions.get(id) ?? id);
const formattedManifest = await format(JSON.stringify(pkg), {
  ...(await resolveConfig(manifest.pathname)),
  parser: "json-stringify",
});
if (process.argv.includes("--check")) {
  if (manifestText !== formattedManifest)
    throw new Error("Run npm run themes to update the VS Code theme choices");
  if (readFileSync(output, "utf8") !== formatted)
    throw new Error("Run npm run themes to regenerate the theme registry");
} else {
  writeFileSync(output, formatted);
  writeFileSync(manifest, formattedManifest);
}
