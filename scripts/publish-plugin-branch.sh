#!/usr/bin/env bash
# Add one release commit to the `plugin-release` branch (see docs/publishing.md).
#
#   VERSION=1.2.3 SOURCE_SHA=<main commit> FILES_DIR=<dir> bash scripts/publish-plugin-branch.sh
#
# FILES_DIR holds the complete branch content (node scripts/plugin-ref.mjs). The
# script builds a commit from it with a temporary index, so the caller's index
# and working tree stay untouched, and pushes it to REMOTE as a fast-forward
# (never --force) together with the tag plugin-release-v$VERSION. It only ever
# writes BRANCH and that tag.
#
# Idempotent: when the tag already exists nothing happens; when the branch tip
# already has exactly this content no empty commit is made (a missing tag is
# set on the tip).
#
# Environment: VERSION, SOURCE_SHA, FILES_DIR (required); REMOTE (default
# origin); BRANCH (default plugin-release).

set -euo pipefail

: "${VERSION:?VERSION is required}"
: "${SOURCE_SHA:?SOURCE_SHA is required}"
: "${FILES_DIR:?FILES_DIR is required}"
REMOTE="${REMOTE:-origin}"
BRANCH="${BRANCH:-plugin-release}"

if ! [[ "$VERSION" =~ ^[0-9]+\.[0-9]+\.[0-9]+(-[0-9A-Za-z.-]+)?$ ]]; then
  echo "Invalid VERSION: $VERSION" >&2
  exit 2
fi
if ! [[ "$SOURCE_SHA" =~ ^[0-9a-f]{7,64}$ ]]; then
  echo "Invalid SOURCE_SHA: $SOURCE_SHA" >&2
  exit 2
fi
case "$BRANCH" in
  main | master | HEAD)
    echo "Refusing to write to $BRANCH" >&2
    exit 2
    ;;
esac
git check-ref-format "refs/heads/$BRANCH" || {
  echo "Invalid BRANCH: $BRANCH" >&2
  exit 2
}
[ -d "$FILES_DIR" ] || {
  echo "FILES_DIR is not a directory: $FILES_DIR" >&2
  exit 2
}

TAG="plugin-release-v$VERSION"
FILES_DIR="$(cd "$FILES_DIR" && pwd)"
GIT_DIR_ABS="$(git rev-parse --absolute-git-dir)"

# Nothing to do when this release already has its tag.
if [ -n "$(git ls-remote --tags "$REMOTE" "refs/tags/$TAG")" ]; then
  echo "Tag $TAG already exists on $REMOTE; nothing to do."
  exit 0
fi

# Current tip of the branch, if the branch exists.
tip=""
if [ -n "$(git ls-remote --heads "$REMOTE" "refs/heads/$BRANCH")" ]; then
  git fetch --quiet --no-tags "$REMOTE" "refs/heads/$BRANCH"
  tip="$(git rev-parse --verify "FETCH_HEAD^{commit}")"
fi

scratch="$(mktemp -d)"
trap 'rm -rf "$scratch"' EXIT

# Tree of FILES_DIR: an empty temporary index plus FILES_DIR as work tree, so
# files that are no longer in FILES_DIR are gone from the new tree.
export GIT_INDEX_FILE="$scratch/index"
(
  cd "$FILES_DIR"
  GIT_DIR="$GIT_DIR_ABS" GIT_WORK_TREE="$FILES_DIR" \
    git -c core.autocrlf=false -c core.safecrlf=false add --all --force -- .
)
tree="$(GIT_DIR="$GIT_DIR_ABS" git write-tree)"
unset GIT_INDEX_FILE
if [ "$(git ls-tree -r --name-only "$tree" | wc -l)" -eq 0 ]; then
  echo "FILES_DIR is empty; refusing to publish an empty tree." >&2
  exit 1
fi

commit="$tip"
if [ -n "$tip" ] && [ "$(git rev-parse "$tip^{tree}")" = "$tree" ]; then
  echo "Branch $BRANCH already has this content ($tip)."
else
  export GIT_AUTHOR_NAME="github-actions[bot]" GIT_COMMITTER_NAME="github-actions[bot]"
  export GIT_AUTHOR_EMAIL="41898282+github-actions[bot]@users.noreply.github.com"
  export GIT_COMMITTER_EMAIL="$GIT_AUTHOR_EMAIL"
  parent=()
  [ -z "$tip" ] || parent=(-p "$tip")
  commit="$(git commit-tree "$tree" ${parent[@]+"${parent[@]}"} \
    -m "Plugin release $VERSION" \
    -m "Generated by the release workflow from main commit $SOURCE_SHA.")"
  echo "Created $commit for $VERSION (source $SOURCE_SHA)."
fi

# One atomic, non-forced push: the branch moves forward (or is created) and the
# tag appears, or neither happens. When the branch already has the content only
# the tag is pushed.
if [ "$commit" = "$tip" ]; then
  git push "$REMOTE" "$commit:refs/tags/$TAG"
else
  git push --atomic "$REMOTE" "$commit:refs/heads/$BRANCH" "$commit:refs/tags/$TAG"
fi
echo "Published $TAG on $BRANCH at $commit."
